export function makeT(ctx) {
  const en = () => String((ctx.getLocale && ctx.getLocale()) || 'zh').startsWith('en');
  const t = (k, vars = {}) => {
    const s = (en() ? EN : ZH)[k] ?? ZH[k] ?? k;
    return s.replace(/\{(\w+)\}/g, (m, key) => (key in vars ? String(vars[key]) : m));
  };
  t.en = en;
  return t;
}
